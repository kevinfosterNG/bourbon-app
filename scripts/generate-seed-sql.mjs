function quoteString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function quoteNullableString(value) {
  return value ? quoteString(value) : 'null';
}

function quoteBoolean(value) {
  return value ? 'true' : 'false';
}

function quoteTextArray(values) {
  const items = values.map((value) => quoteString(value)).join(', ');
  return `array[${items}]::text[]`;
}

function buildBottleValues() {
  return bottles
    .map((bottle) => {
      return `(${[
        quoteString(bottle.id),
        quoteString(bottle.name),
        quoteString(bottle.distillery),
        Number(bottle.proof),
        quoteString(bottle.category),
        quoteNullableString(bottle.imageUrl),
        quoteTextArray(bottle.flavorTags ?? []),
      ].join(', ')})`;
    })
    .join(',\n  ');
}

function buildStoreValues() {
  return stores
    .map((store) => {
      return `(${[
        quoteString(store.id),
        quoteString(store.name),
        store.lat,
        store.lng,
        quoteString(store.city),
        quoteString(store.state),
        quoteBoolean(store.verified),
      ].join(', ')})`;
    })
    .join(',\n  ');
}

function buildListingValues() {
  return listings
    .map((listing) => {
      return `(${[
        quoteString(listing.id),
        quoteString(listing.bottleId),
        quoteString(listing.storeId),
        listing.price,
        quoteBoolean(listing.inStock),
        quoteNullableString(listing.notes),
        'now()',
      ].join(', ')})`;
    })
    .join(',\n  ');
}

const sql = `-- Generated by scripts/generate-seed-sql.mjs
insert into public.bottles (id, name, distillery, proof, category, image_url, flavor_tags)
values
  ${buildBottleValues()}
on conflict (id) do update set
  name = excluded.name,
  distillery = excluded.distillery,
  proof = excluded.proof,
  category = excluded.category,
  image_url = excluded.image_url,
  flavor_tags = excluded.flavor_tags;

insert into public.stores (id, name, lat, lng, city, state, verified)
values
  ${buildStoreValues()}
on conflict (id) do update set
  name = excluded.name,
  lat = excluded.lat,
  lng = excluded.lng,
  city = excluded.city,
  state = excluded.state,
  verified = excluded.verified;

insert into public.listings (id, bottle_id, store_id, price, in_stock, notes, last_updated)
values
  ${buildListingValues()}
on conflict (id) do update set
  bottle_id = excluded.bottle_id,
  store_id = excluded.store_id,
  price = excluded.price,
  in_stock = excluded.in_stock,
  notes = excluded.notes,
  last_updated = now();
`;

const writeIndex = process.argv.indexOf('--write');
if (writeIndex !== -1) {
  const outputPath = process.argv[writeIndex + 1];
  if (!outputPath) {
    throw new Error('Expected a file path after --write');
  }

  writeFileSync(path.resolve(outputPath), sql, 'utf8');
  console.log(`Wrote seed SQL to ${path.resolve(outputPath)}`);
} else {
  process.stdout.write(sql);
}
